# Version 1
global_num1 = 0
global_num2 = 0

def get_inputs():
    global global_num1, global_num2
    global_num1 = float(input("Enter first number: "))
    global_num2 = float(input("Enter second number: "))

def add_numbers():
    # Using global variables instead of parameters
    print(global_num1 + global_num2)

def subtract_numbers():
    print(global_num1 - global_num2)

# Main program
get_inputs()
print("1. Add")
print("2. Subtract")
choice = input("Choose: ")

if choice == '1':
    add_numbers()
elif choice == '2':
    subtract_numbers()